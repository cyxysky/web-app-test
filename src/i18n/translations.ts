const reverseEn = Object.entries(en).reduce<Record<string, string>>((acc, [source, translated]) => {
  acc[translated] = source;
  return acc;
}, {});

export function normalizeLanguage(value: unknown): Language {
  return value === 'en' ? 'en' : 'zh';
}

export function hasChinese(value: string) {
  return /[\u4e00-\u9fff]/.test(value);
}

function formatParams(value: string, params?: Record<string, string | number>) {
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (match, key) => (
    params[key] === undefined ? match : String(params[key])
  ));
}

function translateDynamicText(language: Language, value: string) {
  if (language !== 'en') {
    const exact = reverseEn[value];
    if (exact) return exact;
    const reverseDynamicRules: Array<[RegExp, (...matches: string[]) => string]> = [
      [/^(\d+) web settings$/, (count) => `${count} 项网页配置`],
    ];
    for (const [pattern, render] of reverseDynamicRules) {
      const match = value.match(pattern);
      if (match) return render(...match.slice(1));
    }
    return value;
  }
  const exact = en[value];
  if (exact) return exact;

  const dynamicRules: Array<[RegExp, (...matches: string[]) => string]> = [
    [/^(.+) 访问密钥（可选）$/, (name) => `${name} access key (optional)`],
    [/^(.+) 访问密钥$/, (name) => `${name} access key`],
    [/^(.+) 服务地址$/, (name) => `${name} service URL`],
    [/^AWS 区域$/, () => 'AWS region'],
    [/^AWS Bedrock Bearer Token（可选）$/, () => 'AWS Bedrock Bearer Token (optional)'],
    [/^(\d+) 项网页配置$/, (count) => `${count} web settings`],
    [/^步骤 (\d+) · 操作前$/, (index) => `Step ${index} · Before`],
    [/^步骤 (\d+) · 操作后$/, (index) => `Step ${index} · After`],
    [/^步骤 (\d+) · (.+) · 截图 (\d+)$/, (index, tool, shot) => `Step ${index} · ${tool} · Screenshot ${shot}`],
    [/^步骤 (\d+) · (.+) · (.+)$/, (index, tool, title) => `Step ${index} · ${tool} · ${translateText('en', title)}`],
    [/^步骤 (\d+)$/, (index) => `Step ${index}`],
    [/^工具截图 · (.+)$/, (name) => `Tool screenshot · ${name}`],
    [/^截图 (\d+)$/, (index) => `Screenshot ${index}`],
    [/^运行 (.+)$/, (id) => `Run ${id}`],
    [/^最后更新(.+)$/, (time) => `Last updated ${time}`],
    [/^已运行 (\d+) 个工具，(\d+) 条失败$/, (tools, failed) => `${tools} tools run, ${failed} failed`],
    [/^已运行 (\d+) 个工具$/, (tools) => `${tools} tools run`],
    [/^步骤 (\d+) · 工具调用 (\d+)$/, (step, tool) => `Step ${step} · Tool call ${tool}`],
    [/^(.+) 次运行$/, (count) => `${count} runs`],
    [/^(.+) 次完成$/, (count) => `${count} completed`],
    [/^最近一次：(.+)$/, (time) => `Latest: ${time}`],
    [/^(.+)，未结束$/, (time) => `${time}, not finished`],
    [/^至 (.+)$/, (time) => `to ${time}`],
    [/^(.+) 步骤$/, (count) => `${count} steps`],
    [/^选择 (.+)$/, (name) => `Select ${name}`],
    [/^放大查看 (.+)$/, (name) => `Preview ${name}`],
    [/^删除 (.+)$/, (name) => `Delete ${name}`],
    [/^父级：(.+)$/, (path) => `Parent: ${path}`],
    [/^确定删除选中的 (\d+) 条执行记录吗？$/, (count) => `Delete ${count} selected run records?`],
    [/^确定删除(.+)吗？关联执行记录会一起移除。$/, (name) => `Delete ${name}? Related run records will also be removed.`],
  ];

  for (const [pattern, render] of dynamicRules) {
    const match = value.match(pattern);
    if (match) return render(...match.slice(1));
  }
  return value;
}

export function translateText(language: Language, value: string, params?: Record<string, string | number>) {
  if (language === 'en' && en[value]) return formatParams(en[value], params);
  if (language === 'zh' && reverseEn[value]) return formatParams(reverseEn[value], params);
  const formatted = formatParams(value, params);
  return translateDynamicText(language, formatted);
}

export function isKnownEnglish(value: string) {
  return Boolean(reverseEn[value]);
}
